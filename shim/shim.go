// Package shim writes small executable wrappers that run one Wuko workflow under its own
// command name, so `deploy staging` can stand in for `wuko run --file ... staging`.
package shim

import (
	"bufio"
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// markerPrefix starts the metadata line that identifies a file as a Wuko shim. Install,
// List, and Remove never touch a file without it.
const markerPrefix = "# wuko-shim: "

// ErrExists reports that a shim of the requested name is already installed.
var ErrExists = errors.New("shim already exists")

// ErrNotShim reports a file that Wuko did not generate.
var ErrNotShim = errors.New("not a Wuko shim")

var validName = regexp.MustCompile(`^[A-Za-z0-9_][A-Za-z0-9._-]*$`)

// Spec describes what a shim runs. Exactly one of File, Workflow, and Locator is set.
type Spec struct {
	// File is an absolute workflow path pinned at install time.
	File string `json:"file,omitempty"`
	// Workflow is a name resolved by discovery each time the shim runs, relative to the
	// directory it is invoked from.
	Workflow string `json:"workflow,omitempty"`
	// Locator is a remote workflow URL or github: locator.
	Locator string `json:"locator,omitempty"`
	Target  string `json:"target,omitempty"`
	// Args are wuko run flags placed before the arguments the shim receives.
	Args []string `json:"args,omitempty"`
}

// Shim is an installed shim.
type Shim struct {
	Name string
	Path string
	Spec Spec
}

// Source describes what the shim runs, for listings.
func (spec Spec) Source() string {
	switch {
	case spec.File != "":
		return spec.File
	case spec.Locator != "":
		return spec.Locator
	default:
		return spec.Workflow
	}
}

func (spec Spec) validate() error {
	set := 0
	for _, value := range []string{spec.File, spec.Workflow, spec.Locator} {
		if value != "" {
			set++
		}
	}
	if set != 1 {
		return errors.New("a shim runs exactly one of a workflow file, name, or remote locator")
	}
	if spec.File != "" && !filepath.IsAbs(spec.File) {
		return fmt.Errorf("shim workflow file must be absolute: %s", spec.File)
	}
	return nil
}

// ValidateName rejects names that are not a plain command name, and "wuko", whose shim
// would run itself forever.
func ValidateName(name string) error {
	if !validName.MatchString(name) {
		return fmt.Errorf("invalid shim name %q: use letters, digits, '.', '_', and '-', not starting with '.' or '-'", name)
	}
	if name == "wuko" {
		return errors.New(`a shim cannot be named "wuko"`)
	}
	return nil
}

// Render returns the POSIX shell script for spec.
func Render(name string, spec Spec) ([]byte, error) {
	if err := spec.validate(); err != nil {
		return nil, err
	}
	metadata, err := json.Marshal(spec)
	if err != nil {
		return nil, fmt.Errorf("encoding shim metadata: %w", err)
	}
	command := []string{"wuko", "run"}
	switch {
	case spec.File != "":
		command = append(command, "--file", spec.File)
	case spec.Locator != "":
		command = append(command, spec.Locator)
	default:
		command = append(command, spec.Workflow)
	}
	if spec.Target != "" {
		command = append(command, spec.Target)
	}
	command = append(command, spec.Args...)
	quoted := make([]string, len(command))
	for index, value := range command {
		quoted[index] = shellQuote(value)
	}
	// wuko itself is resolved from PATH so shims survive upgrades that move the binary.
	quoted[0] = "wuko"
	var script bytes.Buffer
	script.WriteString("#!/bin/sh\n")
	fmt.Fprintf(&script, "# Generated by wuko shim install; remove with: wuko shim uninstall %s\n", name)
	script.WriteString(markerPrefix + string(metadata) + "\n")
	script.WriteString("exec " + strings.Join(quoted, " ") + " \"$@\"\n")
	return script.Bytes(), nil
}

// Parse reads the spec from a shim script. It returns ErrNotShim for any other file.
func Parse(data []byte) (Spec, error) {
	scanner := bufio.NewScanner(bytes.NewReader(data))
	for line := 0; scanner.Scan() && line < 3; line++ {
		text, ok := strings.CutPrefix(scanner.Text(), markerPrefix)
		if !ok {
			continue
		}
		var spec Spec
		if err := json.Unmarshal([]byte(text), &spec); err != nil {
			return Spec{}, fmt.Errorf("decoding shim metadata: %w", err)
		}
		return spec, nil
	}
	return Spec{}, ErrNotShim
}

// Install writes a shim named name into dir. An existing shim is replaced only with force;
// a file Wuko did not generate is never replaced.
func Install(dir, name string, spec Spec, force bool) (Shim, error) {
	if err := ValidateName(name); err != nil {
		return Shim{}, err
	}
	data, err := Render(name, spec)
	if err != nil {
		return Shim{}, err
	}
	path := filepath.Join(dir, name)
	if _, err := read(path); err == nil {
		if !force {
			return Shim{}, fmt.Errorf("%w at %s; rerun with --force to replace it", ErrExists, path)
		}
	} else if errors.Is(err, ErrNotShim) {
		return Shim{}, fmt.Errorf("%s exists and is %w; remove it or choose another name with --as", path, err)
	} else if !errors.Is(err, fs.ErrNotExist) {
		return Shim{}, err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return Shim{}, fmt.Errorf("creating shim directory: %w", err)
	}
	if err := writeExecutable(path, data); err != nil {
		return Shim{}, fmt.Errorf("writing shim %s: %w", path, err)
	}
	return Shim{Name: name, Path: path, Spec: spec}, nil
}

// List returns the shims in dir sorted by name, skipping every other file. A missing
// directory has no shims.
func List(dir string) ([]Shim, error) {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("reading shim directory: %w", err)
	}
	var shims []Shim
	for _, entry := range entries {
		if !entry.Type().IsRegular() {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		spec, err := read(path)
		if errors.Is(err, ErrNotShim) {
			continue
		}
		if err != nil {
			return nil, err
		}
		shims = append(shims, Shim{Name: entry.Name(), Path: path, Spec: spec})
	}
	slices.SortFunc(shims, func(a, b Shim) int { return strings.Compare(a.Name, b.Name) })
	return shims, nil
}

// Remove deletes the shim named name from dir, refusing files Wuko did not generate.
func Remove(dir, name string) (Shim, error) {
	if err := ValidateName(name); err != nil {
		return Shim{}, err
	}
	path := filepath.Join(dir, name)
	spec, err := read(path)
	if errors.Is(err, fs.ErrNotExist) {
		return Shim{}, fmt.Errorf("shim %q is not installed in %s", name, dir)
	}
	if errors.Is(err, ErrNotShim) {
		return Shim{}, fmt.Errorf("%s is %w; leaving it in place", path, err)
	}
	if err != nil {
		return Shim{}, err
	}
	if err := os.Remove(path); err != nil {
		return Shim{}, fmt.Errorf("removing shim %s: %w", path, err)
	}
	return Shim{Name: name, Path: path, Spec: spec}, nil
}

func read(path string) (Spec, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return Spec{}, err
	}
	if !info.Mode().IsRegular() {
		return Spec{}, ErrNotShim
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return Spec{}, fmt.Errorf("reading %s: %w", path, err)
	}
	return Parse(data)
}

func writeExecutable(path string, data []byte) error {
	temporary, err := os.CreateTemp(filepath.Dir(path), ".wuko-shim-*")
	if err != nil {
		return err
	}
	temporaryPath := temporary.Name()
	defer os.Remove(temporaryPath)
	if _, err := temporary.Write(data); err != nil {
		temporary.Close()
		return err
	}
	if err := temporary.Chmod(0o755); err != nil {
		temporary.Close()
		return err
	}
	if err := temporary.Close(); err != nil {
		return err
	}
	return os.Rename(temporaryPath, path)
}

func shellQuote(value string) string { return "'" + strings.ReplaceAll(value, "'", "'\\''") + "'" }
