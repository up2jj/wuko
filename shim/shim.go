// Package shim writes executable wrappers for Wuko workflows and projects.
package shim

import (
	"bytes"
	"encoding/json"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strings"
)

// markerPrefix starts the metadata line that identifies a file as a Wuko shim. Install,
// List, and Remove never touch a file without it.
const markerPrefix = "# wuko-shim: "

// inlineMarker starts a block of commented YAML at the end of an inline shim.
// Payload lines start with "# ", so they cannot be confused with this marker.
const inlineMarker = "#wuko-inline-workflow\n"

// ErrExists reports that a shim of the requested name is already installed.
var ErrExists = errors.New("shim already exists")

// ErrNotShim reports a file that Wuko did not generate.
var ErrNotShim = errors.New("not a Wuko shim")

// errInvalidMetadata reports a Wuko shim whose metadata cannot be used. Such a file is
// still Wuko's own, so Remove and a forced Install may replace it.
var errInvalidMetadata = errors.New("invalid shim metadata")

var validName = regexp.MustCompile(`^[A-Za-z0-9_][A-Za-z0-9._-]*$`)

// Spec describes what a shim runs. Exactly one source field is set.
type Spec struct {
	// Project is an absolute project directory in which to invoke the full Wuko CLI.
	Project string `json:"project,omitempty"`
	// File is an absolute workflow path pinned when the shim is generated.
	File string `json:"file,omitempty"`
	// Workflow is a name resolved by discovery each time the shim runs, relative to the
	// directory it is invoked from.
	Workflow string `json:"workflow,omitempty"`
	// Locator is a remote workflow URL or github: locator.
	Locator string `json:"locator,omitempty"`
	Target  string `json:"target,omitempty"`
	// Args are wuko run flags placed before the arguments the shim receives.
	Args []string `json:"args,omitempty"`
	// MissingMessage overrides the diagnostic printed when Wuko is not on PATH.
	MissingMessage string `json:"missing_message,omitempty"`
	// Inline embeds Content instead of loading File at runtime. File records its source.
	Inline bool `json:"inline,omitempty"`
	// Content is the embedded YAML, stored in a comment block rather than the metadata.
	Content string `json:"-"`
}

// Shim is an installed shim.
type Shim struct {
	Name string
	Path string
	Spec Spec
	// Err reports why a listed Wuko shim has unusable metadata.
	Err error
}

// Source describes what the shim runs, for listings.
func (spec Spec) Source() string {
	switch {
	case spec.Project != "":
		return spec.Project
	case spec.File != "":
		return spec.File
	case spec.Locator != "":
		return spec.Locator
	default:
		return spec.Workflow
	}
}

func (spec Spec) validate() error {
	if spec.Inline {
		if spec.File == "" || spec.Content == "" {
			return errors.New("an inline shim requires a workflow file and non-empty content")
		}
	} else if spec.Content != "" {
		return errors.New("embedded workflow content requires an inline shim")
	}
	set := 0
	for _, value := range []string{spec.Project, spec.File, spec.Workflow, spec.Locator} {
		if value != "" {
			set++
		}
	}
	if set != 1 {
		return errors.New("a shim binds exactly one project, workflow file, name, or remote locator")
	}
	if spec.File != "" && !filepath.IsAbs(spec.File) {
		return fmt.Errorf("shim workflow file must be absolute: %s", spec.File)
	}
	if spec.Project != "" {
		if !filepath.IsAbs(spec.Project) {
			return fmt.Errorf("shim project directory must be absolute: %s", spec.Project)
		}
		if spec.Target != "" || len(spec.Args) != 0 {
			return errors.New("a project shim cannot bake in a target or run flags")
		}
	}
	return nil
}

// ValidateName rejects names that are not a plain command name, and "wuko", whose shim
// would run itself forever.
func ValidateName(name string) error {
	if !validName.MatchString(name) {
		return fmt.Errorf("invalid shim name %q: use letters, digits, '.', '_', and '-', not starting with '.' or '-'", name)
	}
	if name == "wuko" {
		return errors.New(`a shim cannot be named "wuko"`)
	}
	return nil
}

// Render returns the POSIX shell script for spec.
func Render(name string, spec Spec) ([]byte, error) {
	if err := spec.validate(); err != nil {
		return nil, err
	}
	metadata, err := json.Marshal(spec)
	if err != nil {
		return nil, fmt.Errorf("encoding shim metadata: %w", err)
	}
	var script bytes.Buffer
	script.WriteString("#!/bin/sh\n")
	script.WriteString("# Generated by wuko; manage with wuko shim --help\n")
	script.WriteString(markerPrefix + string(metadata) + "\n")
	if spec.Project != "" {
		message := fmt.Sprintf("%s: cannot enter project %s; regenerate this shim", name, spec.Project)
		fmt.Fprintf(&script, "CDPATH= cd %s || { printf '%%s\\n' %s >&2; exit 1; }\n", shellQuote(spec.Project), shellQuote(message))
		writeRuntimeCheck(&script, name, spec.MissingMessage)
		script.WriteString("exec wuko \"$@\"\n")
		return script.Bytes(), nil
	}
	// wuko itself is resolved from PATH so shims survive upgrades that move the binary.
	words := []string{"exec wuko 'run'"}
	switch {
	case spec.Inline:
		// The script is its own workflow file.
		words = append(words, `'--file' "$0"`)
	case spec.File != "":
		words = append(words, "'--file'", shellQuote(spec.File))
	case spec.Locator != "":
		words = append(words, shellQuote(spec.Locator))
	default:
		words = append(words, shellQuote(spec.Workflow))
	}
	if spec.Target != "" {
		words = append(words, shellQuote(spec.Target))
	}
	for _, arg := range spec.Args {
		words = append(words, shellQuote(arg))
	}
	writeRuntimeCheck(&script, name, spec.MissingMessage)
	script.WriteString(strings.Join(words, " ") + " \"$@\"\n")
	if spec.Inline {
		script.WriteString(inlineMarker)
		for line := range strings.SplitSeq(spec.Content, "\n") {
			// Empty lines carry no trailing space, which editors would strip.
			if line == "" {
				script.WriteString("#\n")
			} else {
				script.WriteString("# " + line + "\n")
			}
		}
	}
	return script.Bytes(), nil
}

func writeRuntimeCheck(script *bytes.Buffer, name, message string) {
	if message == "" {
		message = name + ": wuko is not on PATH; install Wuko: https://github.com/up2jj/wuko#install"
	}
	fmt.Fprintf(script, "command -v wuko >/dev/null 2>&1 || { printf '%%s\\n' %s >&2; exit 127; }\n", shellQuote(message))
}

// Parse reads the spec from a shim script. It returns ErrNotShim for any other file.
func Parse(data []byte) (Spec, error) {
	metadata, ok := metadataLine(data)
	if !ok {
		return Spec{}, ErrNotShim
	}
	var spec Spec
	if err := json.Unmarshal(metadata, &spec); err != nil {
		return Spec{}, fmt.Errorf("%w: %w", errInvalidMetadata, err)
	}
	if spec.Inline {
		content, err := inlineContent(data)
		if err != nil {
			return Spec{}, fmt.Errorf("%w: %w", errInvalidMetadata, err)
		}
		spec.Content = string(content)
	}
	if err := spec.validate(); err != nil {
		return Spec{}, fmt.Errorf("%w: %w", errInvalidMetadata, err)
	}
	return spec, nil
}

// InlineWorkflow returns the YAML embedded in an inline shim. ok is false for any file that
// is not an inline shim; err reports an inline shim whose embedded block is unreadable.
func InlineWorkflow(data []byte) (content []byte, ok bool, err error) {
	metadata, ok := metadataLine(data)
	if !ok {
		return nil, false, nil
	}
	var spec struct {
		Inline bool `json:"inline"`
	}
	if json.Unmarshal(metadata, &spec) != nil || !spec.Inline {
		return nil, false, nil
	}
	content, err = inlineContent(data)
	return content, true, err
}

// metadataLine returns the JSON metadata from one of the first three lines.
func metadataLine(data []byte) ([]byte, bool) {
	for range 3 {
		line, rest, _ := bytes.Cut(data, []byte("\n"))
		if value, ok := bytes.CutPrefix(bytes.TrimSuffix(line, []byte("\r")), []byte(markerPrefix)); ok {
			return value, true
		}
		data = rest
	}
	return nil, false
}

func inlineContent(data []byte) ([]byte, error) {
	marker := []byte("\n" + inlineMarker)
	index := bytes.LastIndex(data, marker)
	if index < 0 {
		return nil, errors.New("inline workflow block is missing")
	}
	// Empty lines are rendered as "#", so trailing blank lines are never payload.
	payload := bytes.TrimRight(data[index+len(marker):], "\n")
	content := make([]byte, 0, len(payload))
	for line := range bytes.SplitSeq(payload, []byte("\n")) {
		value, ok := bytes.CutPrefix(line, []byte("#"))
		if !ok {
			return nil, errors.New("invalid inline workflow comment block")
		}
		content = append(content, bytes.TrimPrefix(value, []byte(" "))...)
		content = append(content, '\n')
	}
	return content[:len(content)-1], nil
}

// Install writes a shim named name into dir. An existing shim is replaced only with force;
// a file Wuko did not generate is never replaced.
func Install(dir, name string, spec Spec, force bool) (Shim, error) {
	if err := ValidateName(name); err != nil {
		return Shim{}, err
	}
	data, err := Render(name, spec)
	if err != nil {
		return Shim{}, err
	}
	path := filepath.Join(dir, name)
	if _, err := read(path); err == nil || errors.Is(err, errInvalidMetadata) {
		if !force {
			return Shim{}, fmt.Errorf("%w at %s; rerun with --force to replace it", ErrExists, path)
		}
	} else if errors.Is(err, ErrNotShim) {
		return Shim{}, fmt.Errorf("%s exists and is %w; remove it or choose another name with --as", path, err)
	} else if !errors.Is(err, fs.ErrNotExist) {
		return Shim{}, err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return Shim{}, fmt.Errorf("creating shim directory: %w", err)
	}
	if err := writeExecutable(path, data, force); err != nil {
		if errors.Is(err, fs.ErrExist) {
			return Shim{}, fmt.Errorf("%w at %s; rerun with --force to replace it", ErrExists, path)
		}
		return Shim{}, fmt.Errorf("writing shim %s: %w", path, err)
	}
	return Shim{Name: name, Path: path, Spec: spec}, nil
}

// List returns the shims in dir sorted by name, skipping every other file. A shim with
// unusable metadata is listed with Err set. A missing directory has no shims.
func List(dir string) ([]Shim, error) {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return nil, nil
	}
	if err != nil {
		return nil, fmt.Errorf("reading shim directory: %w", err)
	}
	var shims []Shim
	for _, entry := range entries {
		if !entry.Type().IsRegular() {
			continue
		}
		path := filepath.Join(dir, entry.Name())
		spec, err := read(path)
		if errors.Is(err, ErrNotShim) {
			continue
		}
		if err != nil && !errors.Is(err, errInvalidMetadata) {
			return nil, err
		}
		shims = append(shims, Shim{Name: entry.Name(), Path: path, Spec: spec, Err: err})
	}
	slices.SortFunc(shims, func(a, b Shim) int { return strings.Compare(a.Name, b.Name) })
	return shims, nil
}

// Remove deletes the shim named name from dir, refusing files Wuko did not generate.
func Remove(dir, name string) (Shim, error) {
	if err := ValidateName(name); err != nil {
		return Shim{}, err
	}
	path := filepath.Join(dir, name)
	spec, err := read(path)
	if errors.Is(err, fs.ErrNotExist) {
		return Shim{}, fmt.Errorf("shim %q is not installed in %s", name, dir)
	}
	if errors.Is(err, ErrNotShim) {
		return Shim{}, fmt.Errorf("%s is %w; leaving it in place", path, err)
	}
	if err != nil && !errors.Is(err, errInvalidMetadata) {
		return Shim{}, err
	}
	if err := os.Remove(path); err != nil {
		return Shim{}, fmt.Errorf("removing shim %s: %w", path, err)
	}
	return Shim{Name: name, Path: path, Spec: spec}, nil
}

func read(path string) (Spec, error) {
	info, err := os.Lstat(path)
	if err != nil {
		return Spec{}, err
	}
	if !info.Mode().IsRegular() {
		return Spec{}, ErrNotShim
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return Spec{}, fmt.Errorf("reading %s: %w", path, err)
	}
	return Parse(data)
}

// writeExecutable atomically replaces path with data. Without replace, it fails with
// fs.ErrExist if path appeared since it was checked.
func writeExecutable(path string, data []byte, replace bool) error {
	if !replace {
		return createExecutable(path, data)
	}
	temporary, err := os.CreateTemp(filepath.Dir(path), ".wuko-shim-*")
	if err != nil {
		return err
	}
	temporaryPath := temporary.Name()
	defer os.Remove(temporaryPath)
	if _, err := temporary.Write(data); err != nil {
		temporary.Close()
		return err
	}
	if err := temporary.Chmod(0o755); err != nil {
		temporary.Close()
		return err
	}
	if err := temporary.Close(); err != nil {
		return err
	}
	return os.Rename(temporaryPath, path)
}

func createExecutable(path string, data []byte) error {
	file, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o755)
	if err != nil {
		return err
	}
	_, err = file.Write(data)
	if err == nil {
		// Chmod overrides the umask so every shim is executable.
		err = file.Chmod(0o755)
	}
	if closeErr := file.Close(); err == nil {
		err = closeErr
	}
	if err != nil {
		os.Remove(path)
	}
	return err
}

func shellQuote(value string) string { return "'" + strings.ReplaceAll(value, "'", "'\\''") + "'" }
