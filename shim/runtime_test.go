func TestWorkflowShimForwardsInvocation(t *testing.T) {
	t.Parallel()
	for _, inline := range []bool{false, true} {
		t.Run(map[bool]string{false: "file", true: "inline"}[inline], func(t *testing.T) {
			t.Parallel()
			testWorkflowShimInvocation(t, inline)
		})
	}
}

func testWorkflowShimInvocation(t *testing.T, inline bool) {
	t.Helper()
	root := t.TempDir()
	workflow := filepath.Join(root, "workflow with 'quotes' $dollars `backticks`\nand newline.yaml")
	bin := filepath.Join(root, "bin")
	testfs.MkdirAll(t, bin, 0o755)
	testfs.WriteFile(t, filepath.Join(bin, "wuko"), []byte("#!/bin/sh\nprintf '%s\\000' \"$PWD\" \"$@\"\ncat\nprintf 'runtime stderr' >&2\nexit 23\n"), 0o755)
	spec := Spec{
		File: workflow, Target: "production",
		Args: []string{"--var", "value=it's $literal `text`", "--no-config"},
	}
	if inline {
		spec.Inline = true
		spec.Content = "version: 1\nname: embedded\nsteps: []\n"
	}
	installed, err := Install(bin, "ship", spec, false)
	if err != nil {
		t.Fatal(err)
	}
	caller, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	args := []string{"--dry-run", "--var", "value=runtime's $literal `text`", "", "line\nbreak"}
	command := exec.CommandContext(t.Context(), installed.Path, args...)
	command.Dir = caller
	command.Env = []string{"PATH=" + bin + ":/usr/bin:/bin"}
	command.Stdin = strings.NewReader("stdin payload")
	var stdout, stderr bytes.Buffer
	command.Stdout, command.Stderr = &stdout, &stderr
	var exit *exec.ExitError
	if err := command.Run(); !errors.As(err, &exit) || exit.ExitCode() != 23 {
		t.Fatalf("Run = %v, want exit 23", err)
	}
	file := workflow
	if inline {
		file = installed.Path
	}
	wantArgs := []string{caller, "run", "--file", file, spec.Target}
	wantArgs = append(wantArgs, spec.Args...)
	wantArgs = append(wantArgs, args...)
	want := strings.Join(wantArgs, "\x00") + "\x00stdin payload"
	if diff := cmp.Diff(want, stdout.String()); diff != "" {
		t.Fatalf("stdout (-want +got):\n%s", diff)
	}
	if stderr.String() != "runtime stderr" {
		t.Fatalf("stderr = %q", stderr.String())
	}
}

func TestShimReportsMissingRuntime(t *testing.T) {
	t.Parallel()
	for _, source := range []string{"file", "project", "name", "remote"} {
		t.Run(source, func(t *testing.T) {
			t.Parallel()
			for _, message := range []string{"", "-n 100% 'quoted' $dollars `backticks` $(echo expanded)\ninstall with mise"} {
				t.Run(message, func(t *testing.T) {
					t.Parallel()
					root := t.TempDir()
					spec := Spec{MissingMessage: message}
					switch source {
					case "file":
						spec.File = filepath.Join(root, "workflow.yaml")
					case "project":
						spec.Project = root
					case "name":
						spec.Workflow = "check"
					case "remote":
						spec.Locator = "github:acme/flows@v1:ci.yaml"
					}
					installed, err := Install(root, "tool", spec, false)
					if err != nil {
						t.Fatal(err)
					}
					data, err := os.ReadFile(installed.Path)
					if err != nil {
						t.Fatal(err)
					}
					parsed, err := Parse(data)
					if err != nil {
						t.Fatal(err)
					}
					if diff := cmp.Diff(spec, parsed); diff != "" {
						t.Fatalf("round trip (-want +got):\n%s", diff)
					}
					command := exec.CommandContext(t.Context(), installed.Path)
					command.Env = []string{"PATH="}
					var stdout, stderr bytes.Buffer
					command.Stdout, command.Stderr = &stdout, &stderr
					var exit *exec.ExitError
					if err := command.Run(); !errors.As(err, &exit) || exit.ExitCode() != 127 {
						t.Fatalf("Run = %v, want exit 127", err)
					}
					want := message
					if want == "" {
						want = "tool: wuko is not on PATH; install Wuko: https://github.com/up2jj/wuko#install"
					}
					if diff := cmp.Diff(want+"\n", stderr.String()); diff != "" {
						t.Fatalf("stderr (-want +got):\n%s", diff)
					}
					if stdout.Len() != 0 {
						t.Fatalf("stdout = %q", stdout.String())
					}
				})
			}
		})
	}
}

func TestParseLegacyShimWithoutRuntimeCheck(t *testing.T) {
	t.Parallel()
	data := []byte("#!/bin/sh\n# Generated by wuko shim install\n# wuko-shim: {\"file\":\"/work/check.yaml\",\"args\":[\"--no-config\"]}\nexec wuko 'run' '--file' '/work/check.yaml' '--no-config' \"$@\"\n")
	got, err := Parse(data)
	if err != nil {
		t.Fatal(err)
	}
	want := Spec{File: "/work/check.yaml", Args: []string{"--no-config"}}
	if diff := cmp.Diff(want, got); diff != "" {
		t.Fatalf("legacy spec (-want +got):\n%s", diff)
	}
}
